/**
 * Phase 2.3 + Phase 2.4 — engine-curated default capability catalogue.
 *
 * These definitions reference the CANONICAL tool ids the engine registers. A
 * capability whose implementation tool is NOT registered in the current
 * environment is simply never registered (see engine wiring), so the
 * model never sees a fabricated capability. All of it is advisory metadata:
 * every resolved step still flows through the same tool registry, permission,
 * argument, budget, repeated-action and verification rails.
 *
 * Phase 2.4 adds DETERMINISTIC, application-owned intelligence metadata to
 * every default: a risk class (`risk`), a destructiveness flag
 * (`destructive`), an optional permission ceiling (`maximumPermission`, a
 * bounded policy layer only — the tool permission system stays the real gate)
 * and an optional explicit confirmation requirement (`requiresConfirmation`).
 * These values are authored here at build time and are NEVER overridable by a
 * provider or model.
 */

